/**
 * Translate a static UI key into the chosen language.
 * Falls back to Hindi then English if key/language is missing.
 * Runs in 0ms with zero network / API calls.
 */
export function t(key, lang = 'hi', fallback = '') {
  const langCode = (lang || 'hi').toLowerCase();
  
  if (UI_TRANSLATIONS[langCode] && UI_TRANSLATIONS[langCode][key]) {
    return UI_TRANSLATIONS[langCode][key];
  }
  
  // Alias support for editorialDesk -> editorDesk if key not explicitly present in language
  if (key === 'editorialDesk' && UI_TRANSLATIONS[langCode]?.editorDesk) {
    return UI_TRANSLATIONS[langCode].editorDesk;
  }

  // Try language prefix (e.g. 'zh' for 'zh-TW')
  const basePrefix = langCode.split('-')[0];
  if (UI_TRANSLATIONS[basePrefix] && UI_TRANSLATIONS[basePrefix][key]) {
    return UI_TRANSLATIONS[basePrefix][key];
  }

  // Fallback to Hindi
  if (UI_TRANSLATIONS['hi'] && UI_TRANSLATIONS['hi'][key]) {
    return UI_TRANSLATIONS['hi'][key];
  }

  // Fallback to English
  if (UI_TRANSLATIONS['en'] && UI_TRANSLATIONS['en'][key]) {
    return UI_TRANSLATIONS['en'][key];
  }

  return fallback || key;
}

/**
 * Translate category name into chosen language.
 */
export function translateCategoryName(categoryName, lang = 'hi') {
  if (!categoryName) return '';
  return t(categoryName, lang, categoryName);
}
